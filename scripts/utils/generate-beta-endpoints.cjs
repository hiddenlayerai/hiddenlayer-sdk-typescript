// @ts-check
const fs = require('fs');
const path = require('path');

const resourcesDir = path.resolve(__dirname, '..', '..', 'src', 'resources');
const outputFile = path.resolve(__dirname, '..', '..', 'src', 'lib', 'beta-endpoints.ts');

/**
 * Recursively yields all file paths under `dir`.
 * @param {string} dir
 * @returns {AsyncGenerator<string>}
 */
async function* walk(dir) {
  for await (const d of await fs.promises.opendir(dir)) {
    const entry = path.join(dir, d.name);
    if (d.isDirectory()) yield* walk(entry);
    else if (d.isFile()) yield entry;
  }
}

/**
 * Extracts the class name from an `export class Foo extends APIResource` line.
 * @param {string} source
 * @returns {string | null}
 */
function extractClassName(source) {
  const match = source.match(/export\s+class\s+(\w+)\s+extends\s+APIResource/);
  return match ? match[1] : null;
}

/**
 * Convert a captured URL path into a segment pattern. Literal segments are kept
 * as strings; any segment containing a `${...}` interpolation (i.e. a path
 * parameter) becomes `null`, a wildcard that matches any single segment at
 * request time.
 *
 * @param {string} rawPath
 * @returns {Array<string | null>}
 */
function toSegments(rawPath) {
  return rawPath
    .replace(/^\//, '')
    .split('/')
    .filter((s) => s.length > 0)
    .map((s) => (s.includes('${') ? null : s));
}

/**
 * Finds beta methods in a resource file and returns their path patterns.
 *
 * Walks JSDoc blocks containing [BETA]; the following method's `this._client.<verb>(...)`
 * call gives the URL path. Both static single-quoted paths (`'/foo'`) and dynamic
 * tagged-template paths (`` path`/foo/${id}` ``) are captured — the latter is what
 * the previous single-quote-only regex silently dropped, leaving path-parameter
 * beta endpoints unwarned.
 *
 * @param {string} source
 * @param {string} className
 * @returns {Array<{ segments: Array<string | null>, method: string }>}
 */
function extractBetaMethods(source, className) {
  const results = [];

  const betaPattern = /\/\*\*[\s\S]*?\[BETA\][\s\S]*?\*\/\s*(\w+)\s*\(/g;
  let match;
  while ((match = betaPattern.exec(source)) !== null) {
    const methodName = match[1];
    const afterMethod = source.slice(match.index);
    // Optional `path` tag, then a single-quoted or backtick-delimited path.
    const urlMatch = afterMethod.match(
      /this\._client\.(?:post|get|put|patch|delete)\(\s*(?:path\s*)?[`']([^`']*)[`']/,
    );
    if (urlMatch) {
      results.push({ segments: toSegments(urlMatch[1]), method: `${className}.${methodName}` });
    }
  }

  return results;
}

/** @param {Array<string | null>} segments */
function segmentsKey(segments) {
  return segments.map((s) => (s === null ? '*' : s)).join('/');
}

async function main() {
  /** @type {Array<{ segments: Array<string | null>, method: string }>} */
  const entries = [];

  for await (const file of walk(resourcesDir)) {
    if (!file.endsWith('.ts')) continue;

    const source = await fs.promises.readFile(file, 'utf8');
    const className = extractClassName(source);
    if (!className) continue;

    entries.push(...extractBetaMethods(source, className));
  }

  // Stable output: sort by the rendered path pattern.
  entries.sort((a, b) => segmentsKey(a.segments).localeCompare(segmentsKey(b.segments)));

  const lines = entries.map((e) => {
    const segs = e.segments.map((s) => (s === null ? 'null' : `'${s}'`)).join(', ');
    return `  { segments: [${segs}], method: '${e.method}' },`;
  });

  const output = `/**
 * Auto-generated registry of beta endpoints.
 * DO NOT EDIT — regenerated by scripts/utils/generate-beta-endpoints.cjs
 *
 * Each entry is a path pattern: an array of segments where a string is a literal
 * match and \`null\` is a wildcard matching any single path-parameter segment.
 * Used by checkBetaEndpoint to emit runtime warnings for beta endpoints.
 */
export const BETA_ENDPOINTS: ReadonlyArray<{ segments: ReadonlyArray<string | null>; method: string }> = [
${lines.join('\n')}
];
`;

  await fs.promises.writeFile(outputFile, output, 'utf8');

  console.log(`Wrote ${entries.length} beta endpoint(s) to ${path.relative(process.cwd(), outputFile)}`);
  for (const e of entries) {
    console.log(`  /${segmentsKey(e.segments)} -> ${e.method}`);
  }
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
